-- ==============================================================
-- HE THONG QUAN LY VE XEM PHIM - DATABASE SCHEMA & SEED DATA
-- Database: cinema_booking_db
-- ==============================================================

CREATE DATABASE IF NOT EXISTS cinema_booking_db 
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE cinema_booking_db;

-- 1. Xoa bang neu da ton tai (theo dung thu tu khoa ngoai)
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS seats;
DROP TABLE IF EXISTS showtimes;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS movies;

-- 2. Bang phim (movies)
CREATE TABLE movies (
    id VARCHAR(10) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    genre VARCHAR(100) NOT NULL,
    duration INT NOT NULL,
    age_limit INT NOT NULL,
    status VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Bang khach hang (customers)
CREATE TABLE customers (
    id VARCHAR(10) PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) UNIQUE NOT NULL,
    email VARCHAR(100),
    type VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. Bang suat chieu (showtimes)
CREATE TABLE showtimes (
    id VARCHAR(10) PRIMARY KEY,
    movie_id VARCHAR(10) NOT NULL,
    room_name VARCHAR(50) NOT NULL,
    start_time VARCHAR(50) NOT NULL,
    end_time VARCHAR(50) NOT NULL,
    base_price DOUBLE NOT NULL,
    FOREIGN KEY (movie_id) REFERENCES movies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. Bang ghe phong chieu (seats)
CREATE TABLE seats (
    id VARCHAR(20) PRIMARY KEY,
    showtime_id VARCHAR(10) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    FOREIGN KEY (showtime_id) REFERENCES showtimes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. Bang ve xem phim (tickets)
CREATE TABLE tickets (
    id VARCHAR(10) PRIMARY KEY,
    customer_id VARCHAR(10) NOT NULL,
    showtime_id VARCHAR(10) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    final_price DOUBLE NOT NULL,
    paid BOOLEAN NOT NULL DEFAULT FALSE,
    payment_method VARCHAR(50) DEFAULT NULL,
    FOREIGN KEY (customer_id) REFERENCES customers(id),
    FOREIGN KEY (showtime_id) REFERENCES showtimes(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

